def ensure_official_registry_seeded(db: Session) -> tuple[int, int]:
    """Idempotently register verified official Indian & International sources and baseline records."""
    now = datetime.now(UTC)
    sources_created = 0
    scholarships_created = 0

    url_to_source: dict[str, ScholarshipSource] = {}
    for src_data in OFFICIAL_SOURCES:
        existing_src = db.scalar(
            select(ScholarshipSource).where(ScholarshipSource.url == src_data["url"])
        )
        if not existing_src:
            existing_src = ScholarshipSource(**src_data)
            db.add(existing_src)
            db.flush()
            sources_created += 1
        url_to_source[existing_src.url] = existing_src

    for item in _build_official_scholarships():
        existing = db.scalar(select(Scholarship).where(Scholarship.slug == item["slug"]))
        if existing:
            continue
        src = url_to_source.get(item["source_url"])
        schol = Scholarship(
            **item,
            source_id=src.id if src else None,
            last_checked_at=now,
            last_verified_at=now,
            verification_state="VERIFIED",
            current_version=1,
            is_active=True,
        )
        db.add(schol)
        db.flush()

        db.add(
            ScholarshipVersion(
                scholarship_id=schol.id,
                version_number=1,
                snapshot={
                    "name": schol.name,
                    "status": schol.status,
                    "study_scope": schol.study_scope,
                    "destination_countries": schol.destination_countries,
                    "funding_type": schol.funding_type,
                    "application_deadline": schol.application_deadline.isoformat()
                    if schol.application_deadline
                    else None,
                    "benefit_amount_display": schol.benefit_amount_display,
                    "structured_rules": schol.structured_rules,
                },
                changed_fields={"initial_import": {"old": None, "new": "Verified official baseline"}},
                change_source="official_registry_bootstrap",
                source_url=schol.source_url,
                reviewed=True,
                reviewed_by="system_bootstrap",
                reviewed_at=now,
            )
        )
        scholarships_created += 1

    db.commit()
    return sources_created, scholarships_created
